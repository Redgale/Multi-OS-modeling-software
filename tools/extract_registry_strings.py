"""Lists the command labels and tooltips of core/src/commands.cpp for Qt's translation tools.

The core is plain C++ (no Qt), so lupdate cannot see these strings where they are written.
This writes them as QT_TRANSLATE_NOOP markers (context "Command") into a file lupdate scans;
the app translates them when it builds its actions. The standard CAD names stay English on
purpose: they are what people search for and what tutorials use.

    python3 tools/extract_registry_strings.py core/src/commands.cpp app/registry_strings.h
"""
import re
import sys

ADD = re.compile(r'add\(\{"([^"]+)",\s*"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)",\s*"([^"]*)",\s*"((?:[^"\\]|\\.)*)"')


def main(src: str, dst: str) -> None:
    text = open(src, encoding="utf-8").read()
    seen = []
    for cid, label, _standard, panel, tip in ADD.findall(text):
        for s in (label, tip, panel):
            if s and s not in seen:
                seen.append(s)
    # the constraint table: {"id", "Label", "words"} -> label and "Constraint: words."
    table = re.search(r"const char\* cons\[\]\[3\] = \{(.*?)\};", text, re.S)
    if table:
        for _cid, label, words in re.findall(r'\{"([^"]+)", "([^"]+)", "([^"]+)"\}', table.group(1)):
            for s in (label, f"Constraint: {words}."):
                if s not in seen:
                    seen.append(s)
    with open(dst, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/extract_registry_strings.py from core/src/commands.cpp. Do not edit.\n")
        f.write("// Not compiled: read by lupdate so command labels and tooltips can be translated.\n")
        f.write("#if 0\n")
        for s in seen:
            f.write(f'QT_TRANSLATE_NOOP("Command", "{s}")\n')
        f.write("#endif\n")
    print(f"{len(seen)} strings")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
