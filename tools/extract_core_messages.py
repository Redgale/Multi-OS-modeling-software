"""Lists the core's complete message sentences for Qt's translation tools.

The core (core/src) is plain C++, so its error explanations, step statuses and suggestions
are std::string literals that lupdate cannot see. This collects every literal that is a whole
sentence on its own (starts with a capital, a digit, a quote or a %n placeholder, ends with
. ? or !, has a space, and is not glued to other text with +; literals written next to each
other are one string, as in C++) and writes them as QT_TRANSLATE_NOOP("Core", ...) markers.

Sentences built from values are written in the core as patterns, fmt("The axis '%1' does
not exist.", {name}). Those patterns are also written into a list the app compiles in
(kCorePatterns), so jigapp::coreText can recognise a finished message, translate its
pattern and put the same values back.

    python3 tools/extract_core_messages.py core/src app/core_strings.h
"""
import os
import re
import sys

# one or more string literals separated only by white space (C++ joins them)
LITS = re.compile(r'"(?:[^"\\\n]|\\.)*"(?:\s*"(?:[^"\\\n]|\\.)*")*')
PIECE = re.compile(r'"((?:[^"\\\n]|\\.)*)"')
PLACEHOLDER = re.compile(r"%[1-9]")


def sentences(path: str):
    text = open(path, encoding="utf-8").read()
    # drop comments (a // inside a string literal is rare in the core's messages)
    text = re.sub(r"//[^\n]*", "", text)
    for m in LITS.finditer(text):
        s = "".join(PIECE.findall(m.group(0)))
        before = text[max(0, m.start() - 3):m.start()].strip()
        after = text[m.end():m.end() + 3].strip()
        if before.endswith("+") or after.startswith("+"):
            continue  # part of a sentence built from values
        if not re.match(r"^([A-Z0-9“']|%[1-9])", s) or not re.search(r"[.?!]$", s) or " " not in s:
            continue
        yield s


def main(src: str, dst: str) -> None:
    seen = []
    for name in sorted(os.listdir(src)):
        if name.endswith(".cpp"):
            for s in sentences(os.path.join(src, name)):
                if s not in seen:
                    seen.append(s)
    patterns = [s for s in seen if PLACEHOLDER.search(s)]
    with open(dst, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/extract_core_messages.py from core/src. Do not edit.\n")
        f.write("// Read by lupdate so the core's messages can be translated; only the list of\n")
        f.write("// patterns at the end is compiled (app/Translations.cpp).\n")
        f.write("#pragma once\n")
        f.write("#if 0\n")
        for s in seen:
            if s not in patterns:
                f.write(f'QT_TRANSLATE_NOOP("Core", "{s}")\n')
        f.write("#endif\n\n")
        f.write("// Messages built from values: their patterns, with %1, %2… where the values go.\n")
        f.write("inline const char* const kCorePatterns[] = {\n")
        for s in patterns:
            f.write(f'    QT_TRANSLATE_NOOP("Core", "{s}"),\n')
        f.write("};\n")
    print(f"{len(seen)} strings, {len(patterns)} patterns")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
