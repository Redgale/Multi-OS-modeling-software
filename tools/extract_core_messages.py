"""Lists the core's complete message sentences for Qt's translation tools.

The core (core/src) is plain C++, so its error explanations, step statuses and suggestions
are std::string literals that lupdate cannot see. This collects every literal that is a whole
sentence on its own (starts with a capital, ends with . ? or !, has a space, and is not glued
to other text with +) and writes them as QT_TRANSLATE_NOOP("Core", ...) markers. The app
translates core text where it shows it (jigapp::coreText). Sentences assembled from values
("A 30 mm fillet is too big…") stay English until the core passes them as templates.

    python3 tools/extract_core_messages.py core/src app/core_strings.h
"""
import os
import re
import sys

LIT = re.compile(r'(?<![\w+])\s*"((?:[^"\\]|\\.)+)"\s*(?![\w+"])')


def sentences(path: str):
    text = open(path, encoding="utf-8").read()
    # drop comments
    text = re.sub(r"//[^\n]*", "", text)
    for m in re.finditer(r'"((?:[^"\\]|\\.)+)"', text):
        s = m.group(1)
        before = text[max(0, m.start() - 3):m.start()].strip()
        after = text[m.end():m.end() + 3].strip()
        if before.endswith("+") or after.startswith("+"):
            continue  # part of a sentence built from values
        if not re.match(r"^[A-Z]", s) or not re.search(r"[.?!]$", s) or " " not in s:
            continue
        yield s


def main(src: str, dst: str) -> None:
    seen = []
    for name in sorted(os.listdir(src)):
        if name.endswith(".cpp"):
            for s in sentences(os.path.join(src, name)):
                if s not in seen:
                    seen.append(s)
    with open(dst, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/extract_core_messages.py from core/src. Do not edit.\n")
        f.write("// Not compiled: read by lupdate so the core's messages can be translated.\n")
        f.write("#if 0\n")
        for s in seen:
            f.write(f'QT_TRANSLATE_NOOP("Core", "{s}")\n')
        f.write("#endif\n")
    print(f"{len(seen)} strings")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
