# B-011: keep only the DLLs Jigsmith loads, and list each third-party one with its licence.
#   pwsh packaging/windows/trim-dlls.ps1 -Dist dist -CondaPrefix $env:CONDA_PREFIX
# Needs dumpbin (the MSVC developer environment). Starts from the programs and every DLL in
# a subfolder (Qt plugins), follows their imports through the DLLs in the folder, deletes
# the DLLs nothing reaches, and writes THIRD_PARTY_DLLS.txt: each DLL that came from
# conda-forge with its package, version and licence (read from conda-meta).
param([string]$Dist = "dist", [string]$CondaPrefix = $env:CONDA_PREFIX)

$root = (Resolve-Path $Dist).Path
$local = @{}
Get-ChildItem $root -Filter *.dll | ForEach-Object { $local[$_.Name.ToLower()] = $_.FullName }

# Loaded by name at run time, not imported: keep them whatever dumpbin says.
$always = @("opengl32sw.dll", "d3dcompiler_47.dll")

$queue = New-Object System.Collections.Generic.Queue[string]
Get-ChildItem $root -Filter *.exe | ForEach-Object { $queue.Enqueue($_.FullName) }
Get-ChildItem $root -Recurse -Filter *.dll | Where-Object { $_.DirectoryName -ne $root } | ForEach-Object { $queue.Enqueue($_.FullName) }
$needed = @{}
foreach ($a in $always) { if ($local.ContainsKey($a)) { $needed[$a] = $true } }
while ($queue.Count -gt 0) {
    $file = $queue.Dequeue()
    $deps = & dumpbin /nologo /dependents $file | ForEach-Object { $_.Trim().ToLower() } | Where-Object { $_ -like "*.dll" }
    foreach ($d in $deps) {
        if ($local.ContainsKey($d) -and -not $needed.ContainsKey($d)) {
            $needed[$d] = $true
            $queue.Enqueue($local[$d])
        }
    }
}
$removed = 0
foreach ($name in @($local.Keys)) {
    if (-not $needed.ContainsKey($name)) {
        Remove-Item $local[$name]
        $removed++
    }
}
Write-Host "kept $($needed.Count) DLLs, removed $removed that nothing loads"

# which conda package each kept DLL came from, and its licence
$owner = @{}
if ($CondaPrefix -and (Test-Path "$CondaPrefix/conda-meta")) {
    foreach ($meta in Get-ChildItem "$CondaPrefix/conda-meta" -Filter *.json) {
        $j = Get-Content $meta.FullName -Raw | ConvertFrom-Json
        foreach ($f in $j.files) {
            $n = [System.IO.Path]::GetFileName($f).ToLower()
            if ($n -like "*.dll" -and $needed.ContainsKey($n)) {
                $owner[$n] = "$($j.name) $($j.version)`t$($j.license)"
            }
        }
    }
}
$lines = @("# DLLs shipped with Jigsmith for Windows that come from conda-forge, with their licences.",
           "# Generated by packaging/windows/trim-dlls.ps1. Qt's own DLLs and plugins are listed in THIRD_PARTY_LICENSES.md.",
           "# dll`tpackage version`tlicence")
foreach ($name in ($needed.Keys | Sort-Object)) {
    if ($owner.ContainsKey($name)) { $lines += "$name`t$($owner[$name])" }
}
$lines | Set-Content -Encoding utf8 (Join-Path $root "THIRD_PARTY_DLLS.txt")
Write-Host "listed $($owner.Count) conda-forge DLLs in THIRD_PARTY_DLLS.txt"
